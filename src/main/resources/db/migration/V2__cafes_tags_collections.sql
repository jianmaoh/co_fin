-- Cafes and tags are shared by everyone; collections belong to one user.
-- Kept to SQL that both PostgreSQL and H2 (dev profile) accept.

create table cafe (
    id              bigint generated by default as identity primary key,
    name            varchar(100) not null,
    address         varchar(200),
    google_place_id varchar(255) unique,
    created_by      bigint references app_user (id) on delete set null,
    created_at      timestamp with time zone not null default current_timestamp
);

create table tag (
    id   bigint generated by default as identity primary key,
    name varchar(20) not null unique
);

-- One row per (cafe, tag, user): lets the UI show how many people agree on a tag.
create table cafe_tag (
    id         bigint generated by default as identity primary key,
    cafe_id    bigint not null references cafe (id) on delete cascade,
    tag_id     bigint not null references tag (id) on delete cascade,
    user_id    bigint not null references app_user (id) on delete cascade,
    created_at timestamp with time zone not null default current_timestamp,
    unique (cafe_id, tag_id, user_id)
);
create index idx_cafe_tag_tag on cafe_tag (tag_id);
create index idx_cafe_tag_user on cafe_tag (user_id);

create table cafe_collection (
    id         bigint generated by default as identity primary key,
    owner_id   bigint not null references app_user (id) on delete cascade,
    name       varchar(30) not null,
    created_at timestamp with time zone not null default current_timestamp,
    unique (owner_id, name)
);

create table collection_item (
    id            bigint generated by default as identity primary key,
    collection_id bigint not null references cafe_collection (id) on delete cascade,
    cafe_id       bigint not null references cafe (id) on delete cascade,
    note          varchar(200),
    added_at      timestamp with time zone not null default current_timestamp,
    unique (collection_id, cafe_id)
);
create index idx_collection_item_cafe on collection_item (cafe_id);

-- Roles: 'USER' or 'ADMIN' (the developer account that approves and manages cafes).
alter table app_user add column role varchar(20) default 'USER' not null;

-- A cafe is pending until an admin approves it. Pending cafes can be deleted by their creator;
-- approved cafes only by an admin.
alter table cafe add column approved_at timestamp with time zone;
alter table cafe add column approved_by bigint references app_user (id) on delete set null;

-- One review per user per cafe; editing replaces it.
create table review (
    id         bigint generated by default as identity primary key,
    cafe_id    bigint  not null references cafe (id) on delete cascade,
    user_id    bigint  not null references app_user (id) on delete cascade,
    rating     integer not null check (rating between 1 and 5),
    content    varchar(1000),
    visited_on date,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    unique (cafe_id, user_id)
);
create index idx_review_user on review (user_id);

-- Photos live in the database to keep the app stateless (12-factor) without extra infrastructure.
-- At real scale they would go to object storage (S3/GCS) behind a CDN, with only the key stored here.
create table review_photo (
    id           bigint generated by default as identity primary key,
    review_id    bigint      not null references review (id) on delete cascade,
    content_type varchar(50) not null,
    size_bytes   integer     not null,
    data         bytea       not null,
    created_at   timestamp with time zone not null default current_timestamp
);
create index idx_review_photo_review on review_photo (review_id);
